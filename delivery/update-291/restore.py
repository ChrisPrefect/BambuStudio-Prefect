import base64, hashlib, pathlib, subprocess
root = pathlib.Path(__file__).resolve().parent
parts = sorted(root.glob("source-*.b64"))
if len(parts) != 12: raise SystemExit("Expected exactly 12 reviewed bundle chunks")
data = base64.b64decode("".join(f.read_text(encoding="ascii").strip() for f in parts), validate=True)
if hashlib.sha256(data).hexdigest() != "e2f78bb7fbab3baab05ef076c09ae90e59174ec559cdf6b9b4128d5e3991d02a": raise SystemExit("Bundle checksum mismatch")
bundle = pathlib.Path(".git/prefect-update-291.bundle")
bundle.write_bytes(data)
subprocess.run(["git", "fetch", "--no-tags", "https://github.com/bambulab/BambuStudio.git", "tag", "v02.09.01.70"], check=True)
subprocess.run(["git", "bundle", "verify", str(bundle)], check=True)
subprocess.run(["git", "fetch", str(bundle), "HEAD"], check=True)
delta = base64.b64decode((root/"delta-1.b64").read_text(encoding="ascii").strip(), validate=True)
if hashlib.sha256(delta).hexdigest() != "0fb73438fd03e89c5835d70dde4c027c084ce2476c63bdb8569e5692e9e504dd": raise SystemExit("Delta checksum mismatch")
delta_path = pathlib.Path(".git/prefect-update-291-delta.bundle")
delta_path.write_bytes(delta)
subprocess.run(["git", "bundle", "verify", str(delta_path)], check=True)
subprocess.run(["git", "fetch", str(delta_path), "HEAD"], check=True)
subprocess.run(["git", "checkout", "--detach", "f1e1e7f37d4cc78b115dc35b9e7bca7c1a3ea97e"], check=True)
tree = subprocess.check_output(["git", "rev-parse", "HEAD^{tree}"], text=True).strip()
if tree != "0a018974feea712d93cbfd2229619e10344745a9": raise SystemExit("Source tree mismatch")
print("Reviewed 2.9.1 source restored: f1e1e7f37d4cc78b115dc35b9e7bca7c1a3ea97e", tree)

